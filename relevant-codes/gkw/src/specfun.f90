subroutine calerf ( arg, result, jint )

!*****************************************************************************80
!
!! CALERF computes various forms of the error function.
!
!  Discussion:
!
!    This routine evaluates erf(x), erfc(x), and exp(x*x)*erfc(x)
!    for a real argument x.
!
!  Modified:
!
!    03 April 2007
!
!  Author:
!
!    William Cody
!
!  Reference:
!
!    William Cody,
!    Rational Chebyshev Approximations for the Error Function,
!    Mathematics of Computation,
!    Volume 23, Number 107, July 1969, pages 631-638.
!
!  Parameters:
!
!    Input, real :: ARG, the argument.  If JINT is 1, the
!    argument must be less than XBIG.  If JINT is 2, the argument
!    must lie between XNEG and XMAX.
!
!    Output, real :: RESULT, the value of the function,
!    which depends on the input value of JINT:
!    0, RESULT = erf(x);
!    1, RESULT = erfc(x) = 1 - erf(x);
!    2, RESULT = exp(x*x)*erfc(x) = exp(x*x) - erf(x*x)*erf(x).
!
!    Input, integer :: JINT, chooses the function to be computed.
!    0, erf(x);
!    1, erfc(x);
!    2, exp(x*x)*erfc(x).
!
  implicit none

  real :: a(5)
  real :: arg
  real :: b(4)
  real :: c(9)
  real :: d(8)
  real :: del
  real :: four
  real :: half
  integer :: i
  integer :: jint
  real :: one
  real :: p(6)
  real :: q(5)
  real :: result
  real :: sixten
  real :: sqrpi
  real :: two
  real :: thresh
  real :: x
  real :: xbig
  real :: xden
  real :: xhuge
  real :: xinf
  real :: xmax
  real :: xneg
  real :: xnum
  real :: xsmall
  real :: y
  real :: ysq
  real :: zero
  real :: pi
  real :: xmin
!
!  Mathematical constants
!
  data four /4.0E0/
  data one /1.0E0/
  data half /0.5E0/
  data two /2.0E0/
  data zero /0.0E0/
  data sqrpi /5.6418958354775628695E-1/
  data thresh /0.46875E0/
  data sixten /16.0E0/
  data pi     /3.141592653589793238462643383279E0/
!
!  Machine-dependent constants
!
!  data xinf /1.79E308 /
!  data xneg / -26.628E0 /
!  data xbig /26.543E0 /
!  data xhuge /6.71E7/

    
     XSMALL=epsilon(1.)
     XMIN=tiny(1.)
     XINF=huge(1.)
     XBIG=26.543E0
     XNEG=-26.628E0
     XMAX = min( XINF,1/(sqrt(pi)*XMIN ) )
     XHUGE= 1/(2*sqrt(XSMALL))

!
!  Coefficients for approximation to  erf  in first interval
!
  data a/3.16112374387056560E00,1.13864154151050156E02, &
         3.77485237685302021E02,3.20937758913846947E03, &
         1.85777706184603153E-1/
  data b/2.36012909523441209E01,2.44024637934444173E02, &
         1.28261652607737228E03,2.84423683343917062E03/
!
!  Coefficients for approximation to  erfc  in second interval
!
  data c/5.64188496988670089E-1,8.88314979438837594E0, &
         6.61191906371416295E01,2.98635138197400131E02, &
         8.81952221241769090E02,1.71204761263407058E03, &
         2.05107837782607147E03,1.23033935479799725E03, &
         2.15311535474403846E-8/
  data d/1.57449261107098347E01,1.17693950891312499E02, &
         5.37181101862009858E02,1.62138957456669019E03, &
         3.29079923573345963E03,4.36261909014324716E03, &
         3.43936767414372164E03,1.23033935480374942E03/
!
!  Coefficients for approximation to  erfc  in third interval
!
  data p/3.05326634961232344E-1,3.60344899949804439E-1, &
         1.25781726111229246E-1,1.60837851487422766E-2, &
         6.58749161529837803E-4,1.63153871373020978E-2/
  data q/2.56852019228982242E00,1.87295284992346047E00, &
         5.27905102951428412E-1,6.05183413124413191E-2, &
         2.33520497626869185E-3/

  x = arg
  y = abs ( x )
!
!  Evaluate erf for |X| <= 0.46875.
!
  if ( y <= thresh ) then

    ysq = zero
    if ( xsmall < y ) then
      ysq = y * y
    end if

    xnum = a(5) * ysq
    xden = ysq

    do i = 1, 3
      xnum = ( xnum + a(i) ) * ysq
      xden = ( xden + b(i) ) * ysq
    end do

    result = x * ( xnum + a(4) ) / ( xden + b(4) )

    if ( jint /= 0 ) then
      result = one - result
    end if

    if ( jint == 2 ) then
      result = exp ( ysq ) * result
    end if

    return
!
!  Evaluate erfc for 0.46875 <= |X| <= 4.0.
!
   else if ( y <= four ) then

     xnum = c(9) * y
     xden = y

     do i = 1, 7
       xnum = ( xnum + c(i) ) * y
       xden = ( xden + d(i) ) * y
     end do

     result = ( xnum + c(8) ) / ( xden + d(8) )

     if ( jint /= 2 ) then
       ysq = aint ( y * sixten ) / sixten
       del = ( y - ysq ) * ( y + ysq )
       result = exp ( -ysq * ysq ) * exp ( -del ) * result
     end if
!
!  Evaluate erfc for 4.0 < |X|.
!
   else

     result = zero

     if ( xbig <= y ) then

       if ( jint /= 2 .or. xmax <= y ) then
         go to 300
       end if

       if ( xhuge <= y ) then
         result = sqrpi / y
         go to 300
       end if

     end if

     ysq = one / ( y * y )
     xnum = p(6) * ysq
     xden = ysq
     do i = 1, 4
       xnum = ( xnum + p(i) ) * ysq
       xden = ( xden + q(i) ) * ysq
      end do

      result = ysq * ( xnum + p(5) ) / ( xden + q(5) )
      result = ( sqrpi -  result ) / y

      if ( jint /= 2 ) then
        ysq = aint ( y * sixten ) / sixten
        del = ( y - ysq ) * ( y + ysq )
        result = exp ( -ysq * ysq ) * exp ( -del ) * result
      end if

  end if
!
!  Fix up for negative argument, erf, etc.
!
  300 continue

  if ( jint == 0 ) then

    result = ( half - result ) + half
    if ( x < zero ) then
      result = -result
    end if

  else if ( jint == 1 ) then

    if ( x < zero ) then
      result = two - result
    end if

  else

    if ( x < zero ) then

      if ( x < xneg ) then
        result = xinf
      else
        ysq = aint ( x * sixten ) / sixten
        del = ( x - ysq ) * ( x + ysq )
        y = exp ( ysq * ysq ) * exp ( del )
        result = ( y + y ) - result
      end if

    end if

  end if

  return
end subroutine calerf

subroutine machar ( ibeta, it, irnd, ngrd, machep, negep, iexp, &
  minexp, maxexp, eps, epsneg, xmin, xmax )

!*****************************************************************************80
!
!! MACHAR determines various machine arithmetic parameters.
!
!  Discussion:
!
!    This routine is intended to determine the parameters
!    of the floating-point arithmetic system specified below.
!
!  Modified:
!
!    03 April 2007
!
!  Author:
!
!    William Cody
!
!  Reference:
!
!    William Cody, William Waite,
!    Software Manual for the Elementary Functions,
!    Prentice Hall, 1980,
!    ISBN: 0138220646,
!    LC: QA331.C635.
!
!    Michael Malcolm,
!    Algorithms to Reveal Properties of Floating Point Arithmetic,
!    Communications of the ACM,
!    Volume 15, Number 11, November 1972, pages 949-951.
!
!  Parameters:
!
!    Output, integer :: IBETA, the radix for the floating-point representation
!
!    Output, integer :: IT, the number of base IBETA digits in the floating-point
!    significand.
!
!    Output, integer :: IRND.
!    * 0, if floating-point addition chops;
!    * 1, if floating-point addition rounds, but not in the IEEE style;
!    * 2, if floating-point addition rounds in the IEEE style;
!    * 3, if floating-point addition chops, and there is partial underflow;
!    * 4, if floating-point addition rounds, but not in the IEEE style,
!      and there is partial underflow
!    * 5, if floating-point addition rounds in the IEEE style, and there
!      is partial underflow
!
!    Output, integer :: NGRD, the number of guard digits for multiplication with
!    truncating arithmetic.  It is
!    * 0, if floating-point arithmetic rounds, or if it truncates and only
!      IT base IBETA digits participate in the post-normalization shift of the
!      floating-point significand in multiplication;
!    * 1, if floating-point arithmetic truncates and more than IT base IBETA
!      digits participate in the post-normalization shift of the floating-point
!      significand in multiplication.
!
!    Output, integer :: MACHEP. the largest negative integer such that
!    1.0+FLOAT(IBETA)**MACHEP .NE. 1.0, except that MACHEP is bounded below
!    by  -(IT+3).
!
!    Output, integer :: NEGEPS. the largest negative integer such that
!    1.0-FLOAT(IBETA)**NEGEPS .NE. 1.0, except that NEGEPS is bounded below
!    by  -(IT+3).
!
!    Output, integer :: IEXP, the number of bits (decimal places if IBETA = 10)
!    reserved for the representation of the exponent, including the bias or
!    sign, of a floating-point number.
!
!    Output, integer :: MINEXP, largest magnitude negative integer such that
!    FLOAT(IBETA)**MINEXP is positive and normalized.
!
!    Output, integer :: MAXEXP, the smallest positive power of BETA that
!    overflows.
!
!    Output, real :: EPS, the value FLOAT(IBETA)**MACHEP.
!
!    Output, real :: EPSNEG, the value FLOAT(IBETA)**NEGEPS.
!
!    Output, real :: XMIN, the smallest non-vanishing normalized
!    floating-point power of the radix, that is, XMIN = FLOAT(IBETA)**MINEXP.
!
!    Output, real :: XMAX, the largest finite floating-point number.
!    In particular XMAX = (1.0-EPSNEG)*FLOAT(IBETA)**MAXEXP.
!    On some machines  XMAX  will be only the second, or perhaps third,
!    largest number, being too small by 1 or 2 units in the last digit of
!    the significand.
!
  implicit none

  real :: a
  real :: b
  real :: beta
  real :: betain
  real :: betah
  real :: eps
  real :: epsneg
  integer :: i
  integer :: ibeta
  integer :: iexp
  integer :: irnd
  integer :: it
  integer :: itemp
  integer :: iz
  integer :: j
  integer :: k
  integer :: machep
  integer :: maxexp
  integer :: minexp
  integer :: mx
  integer :: negep
  integer :: ngrd
  integer :: nxres
  real :: one
  real :: t
  real :: temp
  real :: tempa
  real :: temp1
  real :: two
  real :: xmax
  real :: xmin
  real :: y
  real :: z
  real :: zero

  one = real ( 1.)
  two = one + one
  zero = one - one
!
!  Determine IBETA, BETA ala Malcolm.
!
  a = one
   10 continue
  a = a + a
  temp = a + one
  temp1 = temp - a
  if ( temp1 - one == zero ) then
    go to 10
  end if

  b = one
   20 continue
  b = b + b
  temp = a + b
  itemp = int ( temp - a )
  if ( itemp == 0 ) then
    go to 20
  end if

  ibeta = itemp
  beta = real ( ibeta)
!
!  Determine IT, IRND.
!
  it = 0
  b = one
  100 continue
  it = it + 1
  b = b * beta
  temp = b + one
  temp1 = temp - b
  if ( temp1 - one == zero ) then
    go to 100
  end if

  irnd = 0
  betah = beta / two
  temp = a + betah

  if ( temp - a /= zero ) then
    irnd = 1
  end if

  tempa = a + beta
  temp = tempa + betah

  if ( irnd == 0 .and. temp - tempa /= zero ) then
    irnd = 2
  end if
!
!  Determine NEGEP, EPSNEG.
!
  negep = it + 3
  betain = one / beta
  a = one
  do i = 1, negep
     a = a * betain
  end do

  b = a
  210 continue
  temp = one - a
  if ( temp - one == zero ) then
    a = a * beta
    negep = negep - 1
    go to 210
  end if

  negep = -negep
  epsneg = a
!
!  Determine MACHEP, EPS.
!
  machep = -it - 3
  a = b
  300 continue
  temp = one + a
  if ( temp - one == zero ) then
    a = a * beta
    machep = machep + 1
    go to 300
  end if

  eps = a
!
!  Determine NGRD.
!
  ngrd = 0
  temp = one + eps

  if ( irnd == 0 .and. temp * one - one /= zero ) then
    ngrd = 1
  end if
!
!  Determine IEXP, MINEXP, XMIN.
!
!  Loop to determine largest I and K = 2**I such that
!    (1/BETA) ** (2**(I))
!  does not underflow.
!  Exit from loop is signaled by an underflow.
!
  i = 0
  k = 1
  z = betain
  t = one + eps
  nxres = 0
  400 continue
  y = z
  z = y * y
!
!  Check for underflow here.
!
  a = z * one
  temp = z * t

  if ( a + a == zero .or. y <= abs ( z ) ) then
    go to 410
  end if

  temp1 = temp * betain
  if ( temp1 * beta == z ) then
    go to 410
  end if

  i = i + 1
  k = k + k
  go to 400

  410 continue
  if ( ibeta == 10 ) then
    go to 420
  end if

  iexp = i + 1
  mx = k + k
  go to 450
!
!  This segment is for decimal machines only.
!
  420 continue

  iexp = 2

  iz = ibeta

  430 continue

  if ( iz <= k ) then
    iz = iz * ibeta
    iexp = iexp + 1
    go to 430
  end if

  mx = iz + iz - 1
!
!  Loop to determine MINEXP, XMIN.
!  Exit from loop is signaled by an underflow.
!
  450 continue

  xmin = y
  y = y * betain
!
!  Check for underflow here.
!
  a = y * one
  temp = y * t
  if ( a + a == zero .or. xmin <= abs ( y ) ) then
    go to 460
  end if

  k = k + 1
  temp1 = temp * betain
  if ( temp1 * beta /= y .or. temp == y ) then
    go to 450
  else
    nxres = 3
    xmin = y
  end if

  460 continue

  minexp = -k
!
!  Determine MAXEXP, XMAX.
!
  if ( k + k - 3 < mx .or. ibeta == 10 ) then
    go to 500
  end if

  mx = mx + mx
  iexp = iexp + 1

  500 continue

  maxexp = mx + minexp
!
!  Adjust IRND to reflect partial underflow.
!
  irnd = irnd + nxres
!
!  Adjust for IEEE-style machines.
!
  if ( 2 <= irnd ) then
    maxexp = maxexp - 2
  end if
!
!  Adjust for machines with implicit leading bit in binary
!  significand, and machines with radix point at extreme
!  right of significand.
!
  i = maxexp + minexp

  if ( ibeta == 2 .and. i == 0 ) then
    maxexp = maxexp - 1
  end if

  if ( 20 < i ) then
    maxexp = maxexp - 1
  end if

  if ( a /= y ) then
    maxexp = maxexp - 2
  end if

  xmax = one - epsneg

  if ( xmax * one /= xmax ) then
    xmax = one - beta * epsneg
  end if

  xmax = xmax / ( beta * beta * beta * xmin )
  i = maxexp + minexp + 3

  do j = 1, i
    if ( ibeta == 2 ) then
      xmax = xmax + xmax
    else
      xmax = xmax * beta
    end if
  end do

  return
end subroutine machar

function ren ( k )

!*****************************************************************************80
!
!! REN is a random number generator.
!
!  Discussion:
!
!    This routine is intended for use on computers with
!    fixed point wordlength of at least 29 bits.  It is
!    best if the floating-point significand has at most
!    29 bits.
!
!  Modified:
!
!    03 April 2007
!
!  Author:
!
!    William Cody
!
!  Reference:
!
!    Malcolm Pike, David Hill,
!    Algorithm 266:
!    Pseudo-Random Numbers,
!    Communications of the ACM,
!    Volume 8, Number 10, October 1965, page 605.
!
!  Parameters:
!
!    Input, integer :: K, a seed for the random number generator.
!    (Not actually used.)
!
!    Output, real :: REN, a pseudorandom value.
!
  implicit none

  real    , parameter :: c1 = 2796203.0D+00
  real    , parameter :: c2 = 1.0D-06
  real    , parameter :: c3 = 1.0D-12
  integer :: iy
  integer :: k
  real    :: ren

  save iy

  data iy / 100001 /

  iy = iy * 125
  iy = iy - ( iy / 2796203 ) * 2796203
  ren = real ( iy) / c1 * ( 1.0D+00 + c2 + c3 )

  return
end function ren

subroutine timestamp ( )

!*****************************************************************************80
!
!! TIMESTAMP prints the current YMDHMS date as a time stamp.
!
!  Example:
!
!    31 May 2001   9:45:54.872 AM
!
!  Modified:
!
!    06 August 2005
!
!  Author:
!
!    John Burkardt
!
!  Parameters:
!
!    None
!
  implicit none

  character ( len = 8 ) ampm
  integer :: d
  integer :: h
  integer :: m
  integer :: mm
  character ( len = 9 ), parameter, dimension(12) :: month = (/ &
    'January  ', 'February ', 'March    ', 'April    ', &
    'May      ', 'June     ', 'July     ', 'August   ', &
    'September', 'October  ', 'November ', 'December ' /)
  integer :: n
  integer :: s
  integer :: values(8)
  integer :: y

  call date_and_time ( values = values )

  y = values(1)
  m = values(2)
  d = values(3)
  h = values(5)
  n = values(6)
  s = values(7)
  mm = values(8)

  if ( h < 12 ) then
    ampm = 'AM'
  else if ( h == 12 ) then
    if ( n == 0 .and. s == 0 ) then
      ampm = 'Noon'
    else
      ampm = 'PM'
    end if
  else
    h = h - 12
    if ( h < 12 ) then
      ampm = 'PM'
    else if ( h == 12 ) then
      if ( n == 0 .and. s == 0 ) then
        ampm = 'Midnight'
      else
        ampm = 'AM'
      end if
    end if
  end if

  write ( *, '(i2,1x,a,1x,i4,2x,i2,a1,i2.2,a1,i2.2,a1,i3.3,1x,a)' ) &
    d, trim ( month(m) ), y, h, ':', n, ':', s, '.', mm, trim ( ampm )

  return
end subroutine timestamp

