def test_prepare_rhs_trace_run_writes_minimal_patched_tree(tmp_path: Path):
    module = _load_module()
    fake_source = tmp_path / "fake_stella"
    fake_explicit = fake_source / module.TARGET_RELATIVE_SOURCE
    fake_explicit.parent.mkdir(parents=True)
    _write_synthetic_explicit_source(fake_explicit)
    vmec = tmp_path / "wout_w7x.nc"
    vmec.write_bytes(b"fake-vmec")
    output_root = tmp_path / "prepared"

    prepared = module.prepare_stella_w7x_rhs_trace_run(
        stella_source=fake_source,
        input_file=INPUT,
        vmec_file=vmec,
        output_root=output_root,
        trace_step=20,
        tend=2.0,
        delt=0.1,
    )
    metadata = json.loads(prepared.metadata_file.read_text())
    patched_text = prepared.patched_explicit_source.read_text()

    assert prepared.trace_step == 20
    assert prepared.trace_iky == 4
    assert prepared.trace_ikx == 1
    assert metadata["status"] == "prepared_patched_stella_run_pending_execution"
    assert metadata["stella_source"] == str(fake_source)
    assert metadata["stella_source_revision"] == "unknown"
    assert metadata["stella_executable"].endswith(
        "stella/COMPILATION/build_cmake/COMPILATION/stella"
    )
    assert metadata["vmec_source"] == str(vmec)
    assert metadata["trace_step"] == 20
    assert metadata["rhs_units"] == "stella_native_rhs_times_code_dt"
    assert metadata["trace_format"] == "stellarator_gk_stella_rhs_trace_v3"
    assert metadata["velocity_weight_columns"] == ["wgts_vpa", "wgts_mu"]
    assert metadata["rhs_call_column"] == "rhs_call"
    assert metadata["force_explicit_stream_mirror"] is True
    assert metadata["trace_output"].endswith("stellarator_gk_w7x_ky03_rhs_trace.dat")
    assert prepared.build_script.read_text().startswith("#!/usr/bin/env bash")
    assert "STELLA_EXECUTABLE" in prepared.run_script.read_text()
    assert "integer, parameter :: stellarator_gk_trace_step = 20" in patched_text
    assert "nstep = 20" in prepared.input_file.read_text()
    assert "stream_implicit = F" in prepared.input_file.read_text()
