from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
INPUT = ROOT / "fixtures/stella_w7x_mode_structure_run/stella_w7x_adiabatic_electrons.in"


SYNTHETIC_EXPLICIT_SOURCE = """\
module gyrokinetic_equation_explicit
   private
contains
   subroutine add_explicit_gyrokinetic_terms
      use parallelisation_layouts, only: vmu_lo
      complex, dimension(:, :), allocatable :: rhs_ky_swap
      restart_time_step = .false.
      call advance_mirror_explicit(pdf, rhs)
      call advance_wdrifty_explicit(pdf, phi, bpar, rhs)
      call advance_wdriftx_explicit(pdf, phi, bpar, rhs)
      call advance_wstar_explicit(phi, rhs)
      call advance_parallel_streaming_explicit(pdf, phi, bpar, rhs)
      ! if advancing apar, need to convert input pdf back from g to gbar
   end subroutine add_explicit_gyrokinetic_terms
   !****************************************************************************
   !                                      Title
end module gyrokinetic_equation_explicit
"""


def _write_synthetic_explicit_source(path: Path) -> None:
    path.write_text(SYNTHETIC_EXPLICIT_SOURCE, encoding="utf-8")


def _load_module():
    path = ROOT / "scripts/prepare_stella_w7x_rhs_trace_run.py"
    spec = importlib.util.spec_from_file_location("prepare_stella_w7x_rhs_trace_run", path)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = module
    spec.loader.exec_module(module)
    return module


def test_stella_explicit_rhs_trace_patch_is_focused_and_idempotent(tmp_path: Path):
    module = _load_module()
    source = tmp_path / "gyrokinetic_equation_explicit.f90"
    _write_synthetic_explicit_source(source)

    assert module.patch_stella_explicit_rhs_trace(
        source,
        trace_step=123,
        trace_iky=4,
        trace_ikx=1,
    )
    assert not module.patch_stella_explicit_rhs_trace(
        source,
        trace_step=123,
        trace_iky=4,
        trace_ikx=1,
    )
    text = source.read_text()

    assert "stellarator_gk W7-X ky=0.3 RHS trace patch" in text
    assert "integer, parameter :: stellarator_gk_trace_step = 123" in text
    assert "integer, parameter :: stellarator_gk_trace_iky = 4" in text
    assert "integer, parameter :: stellarator_gk_trace_ikx = 1" in text
    assert "stellarator_gk_trace_rhs_call = stellarator_gk_trace_rhs_call + 1" in text
    assert "use grids_velocity, only: vpa, mu, wgts_vpa, wgts_mu" in text
    assert "call stellarator_gk_write_complex_state('pdf_g', 'input_pdf', istep, pdf)" in text
    assert "call stellarator_gk_write_phi_trace(istep, phi)" in text
    assert "denominator_fields(stellarator_gk_trace_iky" in text
    assert "'quasineutrality', 'numerator'" in text
    assert "'quasineutrality', 'denominator'" in text
    assert "'normalization', 'native_state_scale'" in text
    assert "call stellarator_gk_write_rhs_delta('mirror_force'" in text
    assert "call stellarator_gk_write_rhs_delta('magnetic_drift_y'" in text
    assert "call stellarator_gk_write_rhs_delta('magnetic_drift_x'" in text
    assert "call stellarator_gk_write_rhs_delta('equilibrium_drive_wstar'" in text
    assert "call stellarator_gk_write_rhs_delta('parallel_streaming'" in text
    assert "call stellarator_gk_write_complex_state('rhs_total', 'total', istep, rhs)" in text
    assert "record step rhs_call term" in text
    assert "wgts_vpa wgts_mu code_time code_dt real imag" in text
    assert "wgts_vpa(iv), wgts_mu(1, iz, imu)" in text
